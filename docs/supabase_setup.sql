-- 1. Tabel Ringkasan Progres per Siswa (1 baris per siswa)
CREATE TABLE IF NOT EXISTS public.student_progress (
  student_key TEXT PRIMARY KEY,
  nama TEXT NOT NULL,
  kelas TEXT NOT NULL,
  absen TEXT DEFAULT '',
  m1_passed_count INTEGER DEFAULT 0,
  m1_passed_list JSONB DEFAULT '[]'::jsonb,
  latihan_emphasis_ok BOOLEAN DEFAULT false,
  latihan_sop_ok BOOLEAN DEFAULT false,
  kuis_score INTEGER,
  kuis_correct INTEGER,
  kuis_total INTEGER,
  kuis_passed BOOLEAN DEFAULT false,
  m2_submitted BOOLEAN DEFAULT false,
  m2_filename TEXT DEFAULT '',
  m2_file_url TEXT DEFAULT '',
  m3_flow_ok BOOLEAN DEFAULT false,
  m3_checkpoint_passed BOOLEAN DEFAULT false,
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- 2. Tabel Log Aktivitas Evaluasi (riwayat setiap percobaan)
CREATE TABLE IF NOT EXISTS public.evaluation_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_key TEXT NOT NULL,
  nama TEXT NOT NULL,
  kelas TEXT NOT NULL,
  event_type TEXT NOT NULL,
  score INTEGER,
  is_passed BOOLEAN,
  detail JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_eval_logs_student ON public.evaluation_logs (student_key);
CREATE INDEX IF NOT EXISTS idx_eval_logs_created ON public.evaluation_logs (created_at DESC);

-- 3. Aktifkan Row Level Security (RLS) + Policy untuk Akses Kelas (Anon)
ALTER TABLE public.student_progress ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.evaluation_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow anon select student_progress" ON public.student_progress;
CREATE POLICY "Allow anon select student_progress"
  ON public.student_progress FOR SELECT TO anon USING (true);

DROP POLICY IF EXISTS "Allow anon insert student_progress" ON public.student_progress;
CREATE POLICY "Allow anon insert student_progress"
  ON public.student_progress FOR INSERT TO anon WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon update student_progress" ON public.student_progress;
CREATE POLICY "Allow anon update student_progress"
  ON public.student_progress FOR UPDATE TO anon USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon select evaluation_logs" ON public.evaluation_logs;
CREATE POLICY "Allow anon select evaluation_logs"
  ON public.evaluation_logs FOR SELECT TO anon USING (true);

DROP POLICY IF EXISTS "Allow anon insert evaluation_logs" ON public.evaluation_logs;
CREATE POLICY "Allow anon insert evaluation_logs"
  ON public.evaluation_logs FOR INSERT TO anon WITH CHECK (true);

-- 4. Storage Bucket untuk Karya PNG Modul 2
INSERT INTO storage.buckets (id, name, public)
VALUES ('modul2-karya', 'modul2-karya', true)
ON CONFLICT (id) DO NOTHING;

DROP POLICY IF EXISTS "Allow public read modul2-karya" ON storage.objects;
CREATE POLICY "Allow public read modul2-karya"
  ON storage.objects FOR SELECT TO public
  USING (bucket_id = 'modul2-karya');

DROP POLICY IF EXISTS "Allow anon upload modul2-karya" ON storage.objects;
CREATE POLICY "Allow anon upload modul2-karya"
  ON storage.objects FOR INSERT TO anon
  WITH CHECK (bucket_id = 'modul2-karya');

DROP POLICY IF EXISTS "Allow anon update modul2-karya" ON storage.objects;
CREATE POLICY "Allow anon update modul2-karya"
  ON storage.objects FOR UPDATE TO anon
  USING (bucket_id = 'modul2-karya');


-- 5. Grant Privileges eksplisit untuk role anon (wajib di beberapa versi Supabase baru)
GRANT USAGE ON SCHEMA public TO anon;
GRANT SELECT, INSERT, UPDATE ON TABLE public.student_progress TO anon;
GRANT SELECT, INSERT ON TABLE public.evaluation_logs TO anon;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon;
